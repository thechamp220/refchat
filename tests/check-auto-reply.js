'use strict';
const fs = require('fs');
const path = require('path');
const assert = require('node:assert/strict');
const harness = fs.readFileSync(path.join(__dirname, 'check-bait.js'), 'utf8').split('(async () => {')[0];
const { boot, settle, OAUTH, PAGE } = new Function('require', '__dirname', harness + '\nreturn { boot, settle, OAUTH, PAGE };')(require, __dirname);
const CHAT = { tab: { id: 7, url: 'https://kick.com/x' }, frameId: 3 };
const start = { type: 'CSG_AUTO_REPLY_START', name: 'Alice', channel: 'kick/x' };
(async () => {
  const w = boot({ csg_engine: { xaiOAuth: OAUTH }, csg_reply_assist: { enabled: true, learnStyle: false } });
  await settle();
  await w.send(start, CHAT);
  assert.equal(Object.keys(w.store.csg_hand || {}).length, 0, 'only extension pages activate automatic sending');
  assert.equal((await w.send({ ...start, name: 'bad nick' }, PAGE)).ok, false);
  assert.equal((await w.send({ ...start, name: 'moi' }, PAGE)).ok, false);
  assert.equal((await w.send(start, PAGE)).ok, true);
  assert.equal(w.store.csg_reply_assist.enabled, false, 'explicit auto activation leaves draft mode');
  assert.equal(w.store.csg_reply_assist.learnStyle, true);
  assert.equal(w.calls.length, 0, 'activation itself makes no model call');
  assert.equal(w.store.csg_hand.alice.channel, 'kick/x');
  await w.line('Alice', '@moi joli clutch');
  assert.equal(w.sent.length, 1);
  assert.equal(w.sent[0].msg.targetKey, 'alice');
  assert.equal(w.sent[0].msg.targetAt, w.store.csg_hand.alice.at);
  await w.send({ type: 'CSG_HAND_STOP', key: 'alice' }, CHAT);
  await w.line('Alice', '@moi encore un message');
  assert.equal(w.sent.length, 1, 'stop prevents further generation and sending');
  assert.equal(w.calls.length, 1);
  const protectedAuto = boot({ csg_engine: { xaiOAuth: OAUTH } }); await settle();
  await protectedAuto.send(start, PAGE);
  const countBefore = protectedAuto.run('ftLog.length');
  await protectedAuto.send({ type: 'CSG_REPLY_ASSIST_CAPTURE', id: 'protected-auto', author: 'Alice',
    text: '@moi joli clutch', channel: 'kick/x' }, CHAT);
  await settle();
  assert.equal(protectedAuto.sent.length, 1, 'a protected author can receive automatic replies');
  assert.equal(protectedAuto.run('ftLog.length'), countBefore, 'protected messages stay out of moderation');
  const offline = boot({}); await settle();
  assert.equal((await offline.send(start, PAGE)).ok, false);
  assert.equal(Object.keys(offline.store.csg_hand || {}).length, 0);
  const race = boot({ csg_engine: { xaiOAuth: OAUTH } }); await settle();
  race.run('globalThis.__engineDone=null; getEngine=()=>new Promise(resolve=>{__engineDone=resolve;})');
  const activating = race.send(start, PAGE);
  await settle();
  await race.send({ type: 'CSG_HAND_STOP', all: true }, PAGE);
  race.run('__engineDone')({ xaiOAuth: OAUTH });
  assert.equal((await activating).ok, false);
  assert.equal(Object.keys(race.store.csg_hand || {}).length, 0, 'stop cancels an activation still waiting');
  console.log('Auto-réponse : activation explicite, style, contexte, arrêt et courses OK');
  process.exit(0);
})().catch(e => { console.error(e); process.exit(1); });
